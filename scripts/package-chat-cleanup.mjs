import { readFile, mkdir, writeFile } from 'node:fs/promises';
// Produce a single file for Supabase's online Edge Function editor.
const shared = await readFile(new URL('../supabase/functions/_shared/chatCleanup.js', import.meta.url), 'utf8');
const entry = (await readFile(new URL('../supabase/functions/chat-cleanup/index.ts', import.meta.url), 'utf8'))
  .replace("import { runChatCleanup } from '../_shared/chatCleanup.js';\n", '');
const output = new URL('../supabase/dashboard/chat-cleanup.ts', import.meta.url);
await mkdir(new URL('../supabase/dashboard/', import.meta.url), { recursive: true });
await writeFile(output, '// Generated by node scripts/package-chat-cleanup.mjs\n' + entry.split('\n')[0] + '\n' + shared + '\n' + entry.split('\n').slice(1).join('\n'));
console.log('Prepared supabase/dashboard/chat-cleanup.ts for the online editor.');
