const fixtureLaunch = '2027-05-10T00:00:00Z' // Test fixture only; never production configuration.

async function setup(page, state) {
  await page.clock.setFixedTime(new Date('2026-11-10T00:00:00Z'))
  await page.route('**/*', async route => {
    const url = new URL(route.request().url())
    const headers = { 'Access-Control-Allow-Origin': '*', 'Access-Control-Allow-Headers': 'authorization,apikey,content-type,x-client-info', 'Access-Control-Allow-Methods': 'GET,POST,OPTIONS', 'Content-Type': 'application/json' }
    if (route.request().method() === 'OPTIONS') return route.fulfill({ status: 204, headers })
    if (url.pathname.endsWith('/flavio-config')) return route.fulfill({ headers, body: JSON.stringify({ launchAt: fixtureLaunch }) })
    if (url.pathname.endsWith('/flavio-notify')) { state.notifyCalls++; return route.fulfill({ status: state.notifyCalls === 1 ? 503 : 200, headers, body: JSON.stringify(state.notifyCalls === 1 ? { error: 'Please try again.' } : { ok: true }) }) }
    if (url.pathname.endsWith('/advertising-enquiry')) { state.adCalls++; return route.fulfill({ status: state.adCalls === 1 ? 503 : 200, headers, body: JSON.stringify(state.adCalls === 1 ? { error: 'Please try again.' } : { ok: true }) }) }
    if (url.hostname !== 'stationlive.test') return route.abort()
    let relative = url.pathname.replace(/^\/rail-dashboard\//, '')
    if (relative === '/' || !relative || !path.extname(relative)) relative = 'index.html'
    const file = path.resolve(root, relative)
    if (!file.startsWith(root + path.sep)) return route.abort()
    try { await route.fulfill({ body: await fs.readFile(file), contentType: contentTypes[path.extname(file)] || 'application/octet-stream' }) }
    catch { await route.abort() }
  })
  await page.goto('https://stationlive.test/rail-dashboard/', { waitUntil: 'domcontentloaded' })
}

